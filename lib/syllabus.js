// Interleave a unit's items so practice mixes flashcards, quizzes and sentence building.
function unitItems(u) {
  const cards = u.cards.map(([sw, en, note]) => ({ type: "card", key: `s:${u.id}|c|${sw}`, sw, en, note: note || null }));
  const quiz = u.quiz.map(([q, answer, wrong, why]) => ({ type: "quiz", key: `s:${u.id}|q|${q}`, q, answer, wrong, why: why || null }));
  const build = u.build.map(([sw, en]) => ({ type: "build", key: `s:${u.id}|b|${sw}`, sw, en }));
  const out = [];
  while (cards.length || quiz.length || build.length) {
    out.push(...cards.splice(0, 3));
    out.push(...quiz.splice(0, 1));
    out.push(...build.splice(0, 1));
  }
  return out.map((it) => ({ ...it, unit: u.id, topic: u.title }));
}

export const SYLLABUS = UNITS.map((u) => ({ ...u, items: unitItems(u) }));
export const ALL_ITEMS = SYLLABUS.flatMap((u) => u.items);
